import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'assets/styles.css'),'utf8');
const app=fs.readFileSync(path.join(root,'assets/app.js'),'utf8');
const data=fs.readFileSync(path.join(root,'assets/data.js'),'utf8');
const source=fs.readFileSync(path.join(root,'source/DealEngine-Developer-Guide.txt'),'utf8');
const context={window:{}};vm.runInNewContext(data,context);
const docs=context.window.DEALENGINE_DOCS;
assert.equal(docs.endpointCount,28);
assert.equal(docs.endpoints.length,28);
assert.equal(docs.events.length,17);
assert.equal(docs.filters.length,23);
assert.equal(docs.errors.length,6);
assert.equal(new Set(docs.endpoints.map(e=>e.id)).size,28);
assert(docs.endpoints.every(e=>['GET','POST','PATCH'].includes(e.method)));
assert(docs.endpoints.every(e=>e.path.startsWith('/api/v1/')));
assert(docs.endpoints.some(e=>e.path==='/api/v1/deals'&&e.method==='POST'));
assert(docs.endpoints.some(e=>e.path==='/api/v1/leads'&&e.method==='POST'));
assert(docs.endpoints.some(e=>e.path==='/api/v1/reports/{id}/rows'));
assert(docs.endpoints.some(e=>e.path==='/api/v1/transparent/resource-requests/{transparentId}/result'));
assert(!docs.endpoints.some(e=>/\/(invoices|payments)(\/|$)/.test(e.path)));
assert(docs.events.some(e=>e.name==='tags.changed'));
assert(docs.events.some(e=>e.name==='payment.received'));
assert(source.includes('28 of them today.'));
assert(source.includes('410 Gone'));
for(const e of docs.endpoints){assert(source.includes(`${e.method}\t${e.path}\t`),`Not in source: ${e.method} ${e.path}`);}
for(const evt of docs.events){assert(source.includes(evt.name+'\t'),`Not in source: ${evt.name}`);}
for(const src of ['assets/styles.css','assets/data.js','assets/app.js','assets/favicon.svg','source/DealEngine-Developer-Guide.txt'])assert(html.includes(src)||fs.existsSync(path.join(root,src)));
assert(html.includes('id="content"')&&html.includes('id="sidebarNav"'));
assert(app.includes('data-code-lang')&&app.includes('data-route')&&app.includes('searchResults'));
assert(css.includes('@media(max-width:800px)'));
console.log('✓ 28 API endpoints verified against source guide');
console.log('✓ 17 webhook event types verified');
console.log('✓ 23 filter rows and 6 error codes');
console.log('✓ Documented route/permission coverage and static assets');
console.log('All content smoke tests passed.');
